/**
 * The widget's vocabulary, generated into its browser files from every language's `widget` words
 * (i18n/<code>/words.mjs). The browser cannot import these modules, so each file carries a block
 * between two markers; `npm run widget:words` rewrites it, and i18n.test.mjs fails while a block
 * differs from what the languages say.
 */

import { packs } from './languages.mjs';

export const BEGIN = '/* words:begin (generated by `npm run widget:words` from scripts/lib/i18n/<code>/words.mjs: do not edit) */';
export const END = '/* words:end */';

/** The `widget` entries each browser file needs, as one alternation string per entry. */
export const WIDGET_FILES = {
  'storefront-app/extensions/storefront-advisor/assets/advisor-cart.js': ['shopping', 'discountAmount', 'cartPage', 'cartPagePhrase', 'cartAll', 'offerNouns', 'areVerb', 'available', 'offersNow', 'currentOffers', 'eligibility', 'stock', 'promo'],
  'storefront-app/extensions/storefront-advisor/assets/advisor-panel.js': ['order'],
};

/** `{ shopping: 'panier|…|cart|…', … }`: every language's fragments for each entry, in reading order. */
export function widgetWords(keys) {
  return Object.fromEntries(keys.map((key) => [key, packs().flatMap((p) => p.words.widget?.[key] ?? []).join('|')]));
}

/** The block a file carries, indented as its surroundings. */
export function widgetBlock(keys, indent = '  ') {
  return `${indent}${BEGIN}\n${indent}var WORDS = ${JSON.stringify(widgetWords(keys))};\n${indent}${END}`;
}

/** A file's text with its block replaced (line endings kept); null when it has no markers. */
export function withWidgetBlock(source, keys) {
  const begin = source.indexOf(BEGIN);
  const end = source.indexOf(END, begin);
  if (begin < 0 || end < 0) return null;
  const lineStart = source.lastIndexOf('\n', begin) + 1;
  const indent = source.slice(lineStart, begin);
  const eol = source.includes('\r\n') ? '\r\n' : '\n';
  return source.slice(0, lineStart) + widgetBlock(keys, indent).replace(/\n/g, eol) + source.slice(end + END.length);
}
