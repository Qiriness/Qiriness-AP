import assert from 'node:assert/strict';
import test from 'node:test';

import { PGlite } from '@electric-sql/pglite';

import {
  DB_MAX_ROWS,
  buildDelete,
  buildInsert,
  buildRpc,
  buildSelect,
  buildUpdate,
  orderClause,
  parseList,
  pickFunction,
  selectList
} from './supabase-pg-sql.mjs';

// One in-process Postgres for the file: a table with the column types whose
// JSON shape matters (timestamptz, bigint, numeric, jsonb, arrays, uuid).
const db = new PGlite();
await db.exec(`
  create table public.items (
    id bigint generated by default as identity primary key,
    shop_id uuid not null,
    name text,
    amount numeric,
    tags text[] not null default '{}',
    meta jsonb,
    done boolean not null default false,
    created_at timestamptz not null default '2026-10-26T07:27:58.098Z',
    unique (shop_id, name)
  );
  create function public.items_named(p_shop uuid, p_like text default '%') returns setof public.items
    language sql stable as $$ select * from public.items where shop_id = p_shop and name like p_like order by id $$;
  create function public.items_count(p_shop uuid) returns bigint
    language sql stable as $$ select count(*) from public.items where shop_id = p_shop $$;
  create function public.items_touch(p_shop uuid) returns void
    language sql as $$ update public.items set done = done where shop_id = p_shop $$;
`);
const SHOP = '11111111-1111-4111-8111-111111111111';
const OTHER = '22222222-2222-4222-8222-222222222222';
const body = async (query) => (await db.query(query.text, query.values)).rows[0]?.body;

test('an insert returns PostgREST-shaped JSON: ISO timestamps, numbers for bigint and numeric, jsonb objects, arrays', async () => {
  const rows = await body(buildInsert({
    table: 'items',
    rows: [
      { shop_id: SHOP, name: 'alpha', amount: 12.5, tags: ['a', 'b'], meta: { notice: 'x', n: 1 } },
      { shop_id: SHOP, name: 'beta', amount: null, tags: [], meta: null }
    ]
  }));
  assert.equal(rows.length, 2);
  assert.equal(rows[0].id, 1);
  assert.equal(typeof rows[0].id, 'number');
  assert.equal(rows[0].amount, 12.5);
  assert.deepEqual(rows[0].tags, ['a', 'b']);
  assert.deepEqual(rows[0].meta, { notice: 'x', n: 1 });
  assert.equal(rows[0].created_at, '2026-10-26T07:27:58.098+00:00');
  assert.equal(rows[0].done, false, 'a column not sent takes its default');
});

test('a minimal insert returns nothing and still writes', async () => {
  const query = buildInsert({ table: 'items', rows: [{ shop_id: OTHER, name: 'gamma' }], minimal: true });
  assert.doesNotMatch(query.text, /RETURNING/);
  await db.query(query.text, query.values);
  assert.equal((await body(buildSelect({ table: 'items', filters: { shop_id: OTHER } }))).length, 1);
});

test('select: columns, aliases, JSON paths and casts, named as PostgREST names them', async () => {
  const rows = await body(buildSelect({
    table: 'items',
    select: 'id,label:name,meta->>notice,n:meta->n,amount::text',
    filters: { shop_id: SHOP, name: 'alpha' }
  }));
  assert.deepEqual(rows, [{ id: 1, label: 'alpha', notice: 'x', n: 1, amount: '12.5' }]);
});

test('filters: is, not.is, in (with quoted items), not.in, comparisons, like with *, cs, ov, a JSON path key', async () => {
  const names = async (filters, order = 'id.asc') =>
    (await body(buildSelect({ table: 'items', select: 'name', filters, order }))).map((row) => row.name);
  assert.deepEqual(await names({ shop_id: SHOP, meta: { operator: 'is', value: 'null' } }), ['beta']);
  assert.deepEqual(await names({ shop_id: SHOP, meta: { operator: 'not.is', value: 'null' } }), ['alpha']);
  assert.deepEqual(await names({ name: { operator: 'in', value: '("alpha","not,there",gamma)' } }), ['alpha', 'gamma']);
  assert.deepEqual(await names({ shop_id: SHOP, name: { operator: 'not.in', value: '(alpha)' } }), ['beta']);
  assert.deepEqual(await names({ id: { operator: 'gte', value: '2' } }), ['beta', 'gamma']);
  assert.deepEqual(await names({ name: { operator: 'like', value: 'al*' } }), ['alpha']);
  assert.deepEqual(await names({ name: { operator: 'ilike', value: '*ETA' } }), ['beta']);
  assert.deepEqual(await names({ tags: { operator: 'cs', value: '{a}' } }), ['alpha']);
  assert.deepEqual(await names({ tags: { operator: 'ov', value: '{b,z}' } }), ['alpha']);
  assert.deepEqual(await names({ meta: { operator: 'cs', value: '{"notice":"x"}' } }), ['alpha']);
  assert.deepEqual(await names({ 'meta->notice': { operator: 'not.is', value: 'null' } }), ['alpha']);
  // A plain value is eq, sent as text. (A boolean or number as text is Postgres's
  // to parse; PGlite type-checks parameters on the client, so that case is
  // proven against production by the parity run, not here.)
  assert.deepEqual(await names({ name: 'beta', shop_id: SHOP }), ['beta']);
  assert.deepEqual(await names({ name: { operator: 'in', value: '()' } }), [], 'an empty list matches nothing');
});

test('order with direction and nulls placement; limit and offset', async () => {
  const rows = await body(buildSelect({ table: 'items', select: 'name', order: 'amount.desc.nullslast,id.asc', limit: 2, offset: 1 }));
  assert.deepEqual(rows.map((row) => row.name), ['beta', 'gamma']);
  assert.equal(orderClause('updated_at.desc'), ' ORDER BY "updated_at" DESC');
  assert.equal(orderClause('a.asc.nullsfirst'), ' ORDER BY "a" ASC NULLS FIRST');
});

test('a read never returns more than db-max-rows, whatever limit is asked for', () => {
  assert.match(buildSelect({ table: 'items' }).text, new RegExp(`LIMIT ${DB_MAX_ROWS}\\)`));
  assert.match(buildSelect({ table: 'items', limit: 5000 }).text, new RegExp(`LIMIT ${DB_MAX_ROWS}\\)`));
  assert.match(buildSelect({ table: 'items', limit: 1 }).text, /LIMIT 1\)/);
});

test('an empty result is [], not null', async () => {
  assert.deepEqual(await body(buildSelect({ table: 'items', filters: { name: 'nobody' } })), []);
});

test('upsert overwrites the columns sent on conflict and returns the row', async () => {
  const [row] = await body(buildInsert({ table: 'items', rows: [{ shop_id: SHOP, name: 'alpha', amount: 99 }], onConflict: 'shop_id,name' }));
  assert.equal(row.id, 1);
  assert.equal(row.amount, 99);
  assert.deepEqual(row.tags, ['a', 'b'], 'a column not sent is left as it was');
});

test('update: one column or several, the WHERE on the table, representation shaped by select', async () => {
  const one = await body(buildUpdate({ table: 'items', filters: { id: 2 }, row: { done: true } }));
  assert.equal(one[0].done, true);
  const shaped = await body(buildUpdate({ table: 'items', filters: { shop_id: SHOP, name: 'alpha' }, row: { amount: 1, meta: { a: [1, 2] } }, select: 'id' }));
  assert.deepEqual(shaped, [{ id: 1 }]);
  const none = await body(buildUpdate({ table: 'items', filters: { id: 999 }, row: { done: true } }));
  assert.deepEqual(none, []);
  const minimal = buildUpdate({ table: 'items', filters: { id: 1 }, row: { done: false }, minimal: true });
  assert.doesNotMatch(minimal.text, /RETURNING/);
  await db.query(minimal.text, minimal.values);
});

test('rpc: a set of rows is an array, a scalar is the bare value, void is null; defaults apply', async () => {
  const named = { name: 'items_named', argTypes: { p_shop: 'uuid', p_like: 'text' }, required: ['p_shop'], returnsSet: true, returnsRows: true, returnsVoid: false };
  const rows = await body(buildRpc({ fn: named, args: { p_shop: SHOP } }));
  assert.deepEqual(rows.map((row) => row.name), ['alpha', 'beta']);
  const filtered = await body(buildRpc({ fn: named, args: { p_shop: SHOP, p_like: 'b%' } }));
  assert.deepEqual(filtered.map((row) => row.name), ['beta']);

  const count = { name: 'items_count', argTypes: { p_shop: 'uuid' }, required: ['p_shop'], returnsSet: false, returnsRows: false, returnsVoid: false };
  assert.equal(await body(buildRpc({ fn: count, args: { p_shop: SHOP } })), 2);

  const touch = { name: 'items_touch', argTypes: { p_shop: 'uuid' }, required: ['p_shop'], returnsSet: false, returnsRows: false, returnsVoid: true };
  const query = buildRpc({ fn: touch, args: { p_shop: SHOP } });
  assert.equal(query.void, true);
  await db.query(query.text, query.values);
});

test('pickFunction chooses the overload by argument names and refuses an ambiguous or missing one', () => {
  const a = { name: 'f', argTypes: { p_shop: 'uuid' }, required: ['p_shop'] };
  const b = { name: 'f', argTypes: { p_shop: 'uuid', p_x: 'int' }, required: ['p_shop', 'p_x'] };
  assert.equal(pickFunction([a, b], 'f', ['p_shop']), a);
  assert.equal(pickFunction([a, b], 'f', ['p_shop', 'p_x']), b);
  assert.throws(() => pickFunction([a], 'f', ['p_y']), /no function/);
  assert.throws(() => pickFunction([], 'f', []), /no function/);
});

test('delete returns the rows it removed, or nothing when minimal', async () => {
  const removed = await body(buildDelete({ table: 'items', filters: { shop_id: OTHER } }));
  assert.deepEqual(removed.map((row) => row.name), ['gamma']);
  assert.doesNotMatch(buildDelete({ table: 'items', filters: { id: 1 }, minimal: true }).text, /RETURNING/);
});

test('what the transport does not understand, it refuses instead of guessing', () => {
  assert.throws(() => selectList('id,customer:customers(id,email)'), /Embedded resources/);
  assert.throws(() => buildSelect({ table: 'items', filters: { or: '(a.eq.1,b.eq.2)' } }), /Logical filter/);
  assert.throws(() => buildSelect({ table: 'items', filters: { name: { operator: 'fts', value: 'x' } } }), /not supported/);
  assert.throws(() => buildSelect({ table: 'items', filters: { name: { operator: 'is', value: 'maybe' } } }), /is\. filter/);
  assert.throws(() => selectList('a;drop table x'), /Unsupported column/);
  assert.throws(() => buildUpdate({ table: 'items', filters: {}, row: {} }), /at least one column/);
});

test('identifiers are quoted and values are parameters, never spliced', () => {
  const query = buildSelect({ table: 'it"ems', filters: { name: "x'); drop table items; --" } });
  assert.match(query.text, /"public"\."it""ems"/);
  assert.doesNotMatch(query.text, /drop table/);
  assert.deepEqual(query.values, ["x'); drop table items; --"]);
});

test('parseList: PostgREST quoting and escapes', () => {
  assert.deepEqual(parseList('(a,b)'), ['a', 'b']);
  assert.deepEqual(parseList('( a , b )'), ['a', 'b']);
  assert.deepEqual(parseList('("a,b","c\\"d")'), ['a,b', 'c"d']);
  assert.deepEqual(parseList('()'), []);
  assert.throws(() => parseList('a,b'), /parenthesised/);
});
