// Writes extensions/storefront-advisor/assets/advisor-strings.js: the widget's words in every
// language it has a locale file for, for a page whose language is not Shopify's.
//
//   npm run advisor:widget-strings
//
// WHY (owner, 2026-11-02: « the chatbot text still doesn't change when I change the language »).
// Qiriness translates its storefront with Weglot: Shopify serves every page in French and the
// translation happens in the browser, so the embed's `t` filter only ever gives the French words.
// The loader asks this file for the visitor's language instead (Weglot's, the URL's or the page's).
//
// GENERATED, NEVER EDITED. The keys come from the embed itself (advisor-embed.liquid: every
// `"key": {{ 'path' | t … }}` line, under the section it sits in) and the words from locales/*.json,
// so a string added to the embed is here after one run. advisor-strings.test.mjs fails when stale.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const EXTENSION = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../extensions/storefront-advisor');
export const OUTPUT = path.join(EXTENSION, 'assets', 'advisor-strings.js');

/** Config path → locale key, read from the embed's JSON config. */
export function configMap(liquid) {
  const map = {};
  const stack = [];
  const config = liquid.slice(liquid.indexOf('id="storefront-advisor-config"'), liquid.indexOf('</script>'));
  for (const line of config.split('\n')) {
    const open = line.match(/^\s*"(\w+)": \{\s*$/);
    if (open) { stack.push(open[1]); continue; }
    if (/^\s*\},?\s*$/.test(line)) { stack.pop(); continue; }
    for (const m of line.matchAll(/\{"id": "(\w+)", "label": \{\{ '([a-z_.]+)' \| t/g)) map[`quickActions.${m[1]}`] = m[2];
    const t = line.match(/^\s*"(\w+)": \{\{ '([a-z_.]+)' \| t\b/);
    if (t) map[[...stack, t[1]].join('.')] = t[2];
  }
  // Theme settings that fall back to a translation: the setting, when filled, is the merchant's own text.
  map['strings.greeting'] = 'advisor.greeting';
  map['strings.launcher'] = 'advisor.launcher';
  map['banner.text'] = 'banner.text';
  map['banner.button'] = 'banner.button';
  return map;
}

/** Locale code → { locale key → text }, from locales/<code>.json (fr.default.json is French). */
export function localeTexts(dir = path.join(EXTENSION, 'locales')) {
  const out = {};
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const code = file.split('.')[0];
    const flat = {};
    const walk = (node, prefix) => {
      for (const [k, v] of Object.entries(node)) {
        if (v && typeof v === 'object') walk(v, `${prefix}${k}.`);
        else flat[`${prefix}${k}`] = v;
      }
    };
    walk(JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8')), '');
    out[code] = flat;
  }
  return out;
}

export function buildWidgetStrings(liquid = fs.readFileSync(path.join(EXTENSION, 'blocks', 'advisor-embed.liquid'), 'utf8')) {
  const map = configMap(liquid);
  const texts = localeTexts();
  const keys = [...new Set(Object.values(map))].sort();
  const languages = Object.fromEntries(Object.entries(texts).map(([code, flat]) => [code, Object.fromEntries(keys.filter((k) => typeof flat[k] === 'string').map((k) => [k, flat[k]]))]));
  return `/* GENERATED by \`npm run advisor:widget-strings\` from locales/*.json and the embed's config: never edit by hand. */
(function () {
  'use strict';
  var MAP = ${JSON.stringify(map)};
  var LANGUAGES = ${JSON.stringify(languages)};

  /* The visitor's language: Weglot's, else the URL's (« /de/… »), else the page's; one this file has. */
  function detect() {
    var lang = '';
    try { lang = window.Weglot && typeof window.Weglot.getCurrentLang === 'function' ? window.Weglot.getCurrentLang() : ''; } catch (e) { lang = ''; }
    if (!lang) lang = (window.location.pathname.match(/^\\/([a-z]{2})(?:\\/|$)/) || [])[1] || '';
    if (!lang) lang = document.documentElement.lang || '';
    lang = String(lang).slice(0, 2).toLowerCase();
    return LANGUAGES[lang] ? lang : '';
  }

  /* The config's words in that language. A setting the merchant filled (greeting, help bubble, banner) stays theirs. */
  function apply(config, lang) {
    var words = LANGUAGES[lang];
    if (!words) return false;
    var custom = config.custom || {};
    var skip = { 'strings.greeting': custom.greeting, 'strings.launcher': custom.launcherText, 'banner.text': custom.bannerText, 'banner.button': custom.bannerButton };
    Object.keys(MAP).forEach(function (where) {
      var text = words[MAP[where]];
      if (typeof text !== 'string' || skip[where]) return;
      text = text.replace(/\\{\\{\\s*shop\\s*\\}\\}/g, config.shopName || '');
      var parts = where.split('.');
      if (parts[0] === 'quickActions') {
        (config.quickActions || []).forEach(function (a) { if (a && a.id === parts[1]) a.label = text; });
        return;
      }
      var node = config;
      for (var i = 0; i < parts.length - 1; i++) node = node[parts[i]] = node[parts[i]] || {};
      node[parts[parts.length - 1]] = text;
    });
    config.context = config.context || {};
    config.context.locale = lang;
    return true;
  }

  /* Weglot answers once it has started: wait for it, at most 1.5 s. */
  function ready(done) {
    var w = window.Weglot;
    var once = function () { if (done) { var d = done; done = null; d(); } };
    if (w && !w.initialized && typeof w.on === 'function') {
      try { w.on('initialized', once); } catch (e) { once(); }
      setTimeout(once, 1500);
    } else once();
  }

  window.StorefrontAdvisorStrings = { detect: detect, apply: apply, ready: ready };
})();
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUTPUT, buildWidgetStrings());
  console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} (${fs.statSync(OUTPUT).size} bytes).`);
}
