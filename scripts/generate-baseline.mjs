// Read-only: writes the schema baseline from the live database's catalogue.
//
//   npm run db:generate:baseline       writes supabase/migrations/00_baseline.sql and
//                                      00_baseline.catalog.json (what a fresh build must equal)
//   node scripts/generate-baseline.mjs --describe <out.json>    the description only, anywhere
//
// Uses SUPABASE_DB_URL (production). See scripts/lib/schema-catalog.mjs for what
// is generated and why it is trusted (a database built from the file must be
// described identically — scripts/check-baseline.mjs).
import { writeFileSync } from 'node:fs';
import pg from 'pg';

import { describeCatalog, generateBaseline } from './lib/schema-catalog.mjs';
import { loadEnv } from './lib/sync-config.mjs';

const args = process.argv.slice(2);
const describe = args[0] === '--describe';
const out = describe ? args[1] : new URL('../supabase/migrations/00_baseline.sql', import.meta.url);
const catalogOut = new URL('../supabase/migrations/00_baseline.catalog.json', import.meta.url);
if (describe && !out) {
  console.error('Usage: node scripts/generate-baseline.mjs [--describe <out.json>]');
  process.exit(1);
}

const HEADER = `-- ============================================================================
-- 00 — THE SCHEMA, AS PRODUCTION HAS IT
--
-- GENERATED by scripts/generate-baseline.mjs from the production catalogue on
-- ${new Date().toISOString().slice(0, 10)}. Do not edit by hand: change the schema with a new numbered
-- migration (01_…, 02_… after this file), then regenerate this file once that
-- migration is applied, so a fresh database and production stay one thing.
--
-- WHAT IT IS FOR. Building a NEW database (another company, a dev project, a
-- test): run this file once on an empty Supabase project, then the files in
-- supabase/seeds/ after the first shop exists. Production never runs it.
--
-- WHY IT REPLACED THE OLD CHAIN (2026-10-13). 98 files, 01_foundation to
-- 96_order_lines, no longer built a fresh database: 8 of them fail on one
-- (functions re-created with new signatures, a table created twice, views
-- dropping columns), so the repo could not reproduce production. They are kept,
-- unrun, in supabase/migrations/archive/ for their history and prose.
--
-- PROVEN by scripts/check-baseline.mjs: a database built from this file is
-- described identically to production (tables, columns, defaults, generated
-- columns, constraints, indexes, views, functions, triggers, RLS, privileges,
-- comments, the chat role).
--
-- NOT HERE: data (supabase/seeds/), the chat role's password (the operator's),
-- what Supabase provides (auth, storage, vault internals, pg_stat_statements).
-- ============================================================================`;

const env = loadEnv();
const client = new pg.Client({ connectionString: env.SUPABASE_DB_URL, ssl: { rejectUnauthorized: false } });
await client.connect();
try {
  await client.query('begin read only');
  if (describe) {
    writeFileSync(out, JSON.stringify(await describeCatalog(client), null, 1));
  } else {
    writeFileSync(out, await generateBaseline(client, { header: HEADER }));
    writeFileSync(catalogOut, `${JSON.stringify(await describeCatalog(client), null, 1)}
`);
    console.log(`wrote ${catalogOut.pathname}`);
  }
  console.log(`wrote ${out.pathname ?? out}`);
} finally {
  await client.query('rollback').catch(() => {});
  await client.end();
}
