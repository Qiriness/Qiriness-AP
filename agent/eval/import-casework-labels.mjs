import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { validateLabel } from './casework-vocabulary.mjs';
import { isTouched } from './score-casework.mjs';

// Folds a `casework-labels.json` export into the checked-in set.
//
//   npm run cases:import -- <path/to/casework-labels.json>
//
// BATCHES ACCUMULATE. The set is keyed on the message id; a later export
// replaces the label for a message it carries and leaves every other one alone,
// so labelling in sittings needs no bookkeeping.
//
// IDS AND CHOICES ONLY. The export has no bodies and neither does the output;
// the runner reads the mail live, as `eval:closure` does. The labeller's notes
// are kept — they are the reasoning a later disagreement will be argued from —
// and are the one free-text field, so read them in the diff before committing.
//
// ONLY WHAT A PERSON DECIDED. A suggestion nobody touched is dropped (see
// `isTouched`), and a value outside the vocabulary is dropped and printed.

const OUT = fileURLToPath(new URL('./casework-cases.mjs', import.meta.url));

const inPath = process.argv[2];
if (!inPath) {
  console.error('usage: npm run cases:import -- <casework-labels.json>');
  process.exit(1);
}

const exported = JSON.parse(readFileSync(inPath, 'utf8'));
const existing = existsSync(OUT) ? (await import(`${new URL('./casework-cases.mjs', import.meta.url)}?t=${Date.now()}`)).CASEWORK_CASES : [];
const byMessage = new Map(existing.map((row) => [row.messageId, row]));

let added = 0;
let replaced = 0;
let untouched = 0;
const problems = [];
for (const [messageId, raw] of Object.entries(exported.labels ?? {})) {
  if (!isTouched(raw)) {
    untouched += 1;
    continue;
  }
  const direction = raw.direction === 'outbound' ? 'outbound' : 'inbound';
  const { label, dropped, notApplicable } = validateLabel(raw, { direction });
  if (dropped.length) problems.push(`${messageId.slice(0, 8)} valeur inconnue : ${dropped.join(', ')}`);
  if (notApplicable.length) problems.push(`${messageId.slice(0, 8)} (${direction}) ignoré : ${notApplicable.join(', ')}`);
  const { note, ...decisions } = label;
  if (byMessage.has(messageId)) replaced += 1;
  else added += 1;
  byMessage.set(messageId, { ticketId: raw.ticketId, messageId, direction, ...decisions, note });
}

const rows = [...byMessage.values()];
writeFileSync(OUT, render(rows, exported.exportedAt), 'utf8');

console.log(`${added} ajouté(s), ${replaced} remplacé(s), ${untouched} suggestion(s) non touchée(s) ignorée(s).`);
console.log(`${rows.length} message(s) étiqueté(s) sur ${new Set(rows.map((r) => r.ticketId)).size} fil(s) → eval/casework-cases.mjs`);
for (const line of problems) console.log(`  · ${line}`);

function render(rows, exportedAt) {
  return `// The multi-turn labelled set: what the pipeline should decide at each point
// in a thread. GENERATED by \`npm run cases:import\` — edit the labels on the
// review page and re-import rather than editing this file by hand.
//
// IDS AND CHOICES, NEVER BODIES: the runner reads the mail live. Labelled by the
// team on the \`cases:label\` page; last import from an export of ${exportedAt ?? 'unknown date'}.
// Vocabulary: \`casework-vocabulary.mjs\`. Scored by \`npm run eval:casework\`.

export const CASEWORK_CASES = ${JSON.stringify(rows, null, 2)};
`;
}
